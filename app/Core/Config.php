<?php
declare(strict_types=1);

namespace App\Core;

final class Config
{
    private static array $items = [];

    public static function path(): string
    {
        return BASE_PATH . '/config/config.php';
    }

    public static function load(): void
    {
        $file = self::path();
        self::$items = is_file($file) ? (array) require $file : [];
    }

    public static function get(string $key, mixed $default = null): mixed
    {
        return data_get(self::$items, $key, $default);
    }

    public static function all(): array
    {
        return self::$items;
    }

    public static function installed(): bool
    {
        return !empty(self::$items['installed']);
    }

    public static function mode(): string
    {
        return (string) (self::$items['mode'] ?? 'single');
    }

    public static function isMulti(): bool
    {
        return self::mode() === 'multi';
    }

    public static function write(array $items): void
    {
        $php = "<?php\n// Generated by the Matjar installer. Keep this file private.\nreturn " . var_export($items, true) . ";\n";
        if (file_put_contents(self::path(), $php, LOCK_EX) === false) {
            throw new \RuntimeException('Unable to write config/config.php - check folder permissions.');
        }
        @chmod(self::path(), 0640);
        self::$items = $items;
    }
}
